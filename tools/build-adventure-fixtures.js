'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { crc32 } = require('../mod-system/mod-zip-reader.js');
const root = path.resolve(__dirname, '..');
function zip(entries, { deflate = false } = {}) {
  const locals = [], central = []; let offset = 0;
  for (const [name, data] of entries) {
    const n = Buffer.from(name), bytes = Buffer.from(data), crc = crc32(bytes), source = deflate ? require('node:zlib').deflateRawSync(bytes) : bytes;
    const local = Buffer.alloc(30); local.writeUInt32LE(0x04034b50); local.writeUInt16LE(20, 4);
    local.writeUInt16LE(deflate ? 8 : 0, 8); local.writeUInt32LE(crc, 14); local.writeUInt32LE(source.length, 18); local.writeUInt32LE(bytes.length, 22); local.writeUInt16LE(n.length, 26);
    locals.push(local, n, source);
    const cd = Buffer.alloc(46); cd.writeUInt32LE(0x02014b50); cd.writeUInt16LE(20, 4); cd.writeUInt16LE(20, 6);
    cd.writeUInt16LE(deflate ? 8 : 0, 10); cd.writeUInt32LE(crc, 16); cd.writeUInt32LE(source.length, 20); cd.writeUInt32LE(bytes.length, 24); cd.writeUInt16LE(n.length, 28); cd.writeUInt32LE(offset, 42);
    central.push(cd, n); offset += local.length + n.length + source.length;
  }
  const directory = Buffer.concat(central), end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50);
  end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10); end.writeUInt32LE(directory.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, directory, end]);
}
function sampleFiles(type) {
  const base = path.join(root, 'adventure-system/samples', type), entries = [];
  function walk(dir) { for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
    const full = path.join(dir, entry.name); if (entry.isDirectory()) walk(full); else entries.push([path.relative(base, full).split(path.sep).join('/'), fs.readFileSync(full)]);
  } }
  walk(base); return entries;
}
function build() {
  const schemas = Object.fromEntries(['manifest', 'game-data', 'scenarios'].map(name => [name, require(`../adventure-system/schemas/${name}.schema.json`)]));
  fs.writeFileSync(path.join(root, 'adventure-system/adventure-schemas.js'), '/* Generated by tools/build-adventure-fixtures.js from Stage 1 schemas. */\nglobalThis.QRCQAdventureSchemas = ' + JSON.stringify(schemas, null, 2) + ';\n');
  const output = path.join(root, 'adventure-system/samples/packages'); fs.mkdirSync(output, { recursive: true });
  const adventures = [];
  for (const type of ['linear', 'circular', 'non-linear']) {
    const bytes = zip(sampleFiles(type)); fs.writeFileSync(path.join(output, `${type}.zip`), bytes);
    const m = require(`../adventure-system/samples/${type}/manifest.json`);
    const keys = ['id', 'version', 'name', 'description', 'author', 'language', 'type', 'location', 'estimatedMinutes', 'minimumAge'];
    adventures.push({ ...Object.fromEntries(keys.map(k => [k, m[k]])),
      coverUrl: `https://example.invalid/${type}.png`, downloadUrl: `https://example.invalid/${type}.zip`,
      packageSize: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex') });
  }
  fs.writeFileSync(path.join(output, 'catalog.json'), JSON.stringify({ catalogVersion: 1, adventures }, null, 2) + '\n');
}
module.exports = { zip, sampleFiles, build };
if (require.main === module) build();
